#!/usr/bin/env node
/**
 * Creates an independent Expo application from the owned template.
 *
 * Usage: node _expo/starter/generator/create-app.mjs TARGET --plan PLAN.json [--install]
 *
 * TARGET may be a new folder, an empty folder, or a freshly created repository
 * that holds only .git, README, LICENSE and ignore files (see
 * scripts/lib/target.mjs). Existing files are never overwritten. The template
 * itself, and this builder repository, are never modified.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { bashCommand, copyTemplate, ensureGitRepository, inspectTarget } from "../../../scripts/lib/target.mjs";
import { applyPlan, normalizePlan } from "./project-config.mjs";

const generatorDir = path.dirname(fileURLToPath(import.meta.url));
const starterDir = path.dirname(generatorDir);
const expoDir = path.dirname(starterDir);
const builderRoot = path.dirname(expoDir);
const templateDir = path.join(starterDir, "template");
const source = JSON.parse(fs.readFileSync(path.join(starterDir, "SOURCE.json"), "utf8"));

const args = process.argv.slice(2);
const targetArg = args[0];
const planIndex = args.indexOf("--plan");
const install = args.includes("--install");

if (!targetArg || targetArg.startsWith("--") || planIndex < 0 || !args[planIndex + 1]) {
  console.error("Usage: node _expo/starter/generator/create-app.mjs TARGET --plan PLAN.json [--install]");
  process.exit(2);
}

const planFile = path.resolve(args[planIndex + 1]);
// Validate the plan before touching the disk.
normalizePlan(JSON.parse(fs.readFileSync(planFile, "utf8")));
const { target, existing, hasGit } = inspectTarget(targetArg, { builderRoot });

const notes = copyTemplate(templateDir, target, existing);
// LF line endings keep Bash scripts runnable and formatting identical on Windows.
const gitattributes = path.join(target, ".gitattributes");
if (!fs.existsSync(gitattributes)) fs.copyFileSync(path.join(expoDir, "code", "gitattributes"), gitattributes);

const plan = applyPlan(target, JSON.parse(fs.readFileSync(planFile, "utf8")));
const gitNote = ensureGitRepository(target, hasGit);
fs.writeFileSync(
  path.join(target, "SOURCE.md"),
  [
    "# Template source",
    "",
    "Generated by Mobile Starter App Builder (Expo platform) from its owned template.",
    `Originally derived from ${source.upstream}`,
    `Pinned upstream commit: ${source.commit} (captured ${source.captured})`,
    `The upstream ${source.license} license is preserved (LICENSE or licenses/TEMPLATE_LICENSE.txt).`,
    "",
  ].join("\n"),
);

console.log(`Created ${plan.name} (Expo) at ${target}`);
console.log(`Selected capabilities: ${plan.capabilities.join(", ")}`);
for (const note of [...notes, gitNote]) console.log(`  - ${note}`);
if (install) {
  const result = spawnSync(bashCommand(), ["scripts/setup.sh"], { cwd: target, stdio: "inherit", shell: false });
  if (result.status !== 0) process.exit(result.status ?? 1);
} else {
  console.log(`Next: cd "${target}" && bash start.sh setup`);
}
