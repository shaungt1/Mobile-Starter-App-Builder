#!/usr/bin/env node
/**
 * Creates an independent Tauri 2 mobile application from the owned template.
 *
 * Usage: node _tauri2/generator/create-app.mjs TARGET --plan PLAN.json [--install]
 *
 * TARGET may be a new folder, an empty folder, or a freshly created repository
 * that holds only .git, README, LICENSE and ignore files. Existing files are
 * never overwritten. Capabilities listed in the plan are installed after the
 * copy, one at a time, with the same installer as `start.sh tauri capability install`.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { bashCommand, copyTemplate, ensureGitRepository, inspectTarget } from "../../scripts/lib/target.mjs";
import { installCapability } from "./capabilities.mjs";
import { applyPlan, normalizePlan } from "./project-config.mjs";

const generatorDir = path.dirname(fileURLToPath(import.meta.url));
const tauriDir = path.dirname(generatorDir);
const builderRoot = path.dirname(tauriDir);
const templateDir = path.join(tauriDir, "template");
const overlaysDir = path.join(tauriDir, "overlays");

const args = process.argv.slice(2);
const targetArg = args[0];
const planIndex = args.indexOf("--plan");
const install = args.includes("--install");
if (!targetArg || targetArg.startsWith("--") || planIndex < 0 || !args[planIndex + 1]) {
  console.error("Usage: node _tauri2/generator/create-app.mjs TARGET --plan PLAN.json [--install]");
  process.exit(2);
}

const rawPlan = JSON.parse(fs.readFileSync(path.resolve(args[planIndex + 1]), "utf8"));
const checked = normalizePlan(rawPlan);
const { target, existing, hasGit } = inspectTarget(targetArg, { builderRoot });

const notes = copyTemplate(templateDir, target, existing);
const plan = applyPlan(target, rawPlan, overlaysDir);
for (const id of checked.capabilities) notes.push(...installCapability(target, id, { quiet: true }));
// Copy the reference docs so the new app stands alone for people and agents.
fs.cpSync(path.join(tauriDir, "docs", "reference"), path.join(target, "docs", "reference"), { recursive: true });
const gitNote = ensureGitRepository(target, hasGit);
fs.writeFileSync(
  path.join(target, "SOURCE.md"),
  [
    "# Template source",
    "",
    "Generated by Mobile Starter App Builder (Tauri 2 platform) from its owned template.",
    `Frontend: ${plan.frontend}. Interface kit: ${plan.ui}${plan.ui === "konsta" ? ` (${plan.uiTheme})` : ""}.`,
    "The Rust core and interface structure follow create-tauri-app's React + TypeScript template (MIT/Apache-2.0).",
    "",
  ].join("\n"),
);

console.log(`Created ${plan.name} (Tauri 2) at ${target}`);
console.log(`Frontend: ${plan.frontend}; UI: ${plan.ui}; capabilities: ${plan.capabilities.join(", ") || "none"}`);
for (const note of [...notes, gitNote]) console.log(`  - ${note}`);
if (install) {
  const result = spawnSync(bashCommand(), ["scripts/setup.sh"], { cwd: target, stdio: "inherit", shell: false });
  if (result.status !== 0) process.exit(result.status ?? 1);
} else {
  console.log(`Next: cd "${target}" && bash start.sh setup`);
}
